# src/write_results.R — assemble results/RESULTS.md from the Phase 2 tables.

suppressMessages({library(data.table)})

# minimal data.frame -> GitHub markdown table (row-wise, numeric-aware)
md_table <- function(dt, cols = names(dt)) {
  dt <- as.data.frame(dt)[, cols, drop = FALSE]
  fmt_col <- function(x) {
    if (is.numeric(x)) x <- formatC(x, format = "g", digits = 3)
    x <- as.character(x); x[is.na(x)] <- ""; x
  }
  chr <- lapply(dt, fmt_col)                       # list of char vectors, one per column
  body <- vapply(seq_len(nrow(dt)), function(i)
    paste0("| ", paste(vapply(chr, `[`, character(1), i), collapse = " | "), " |"), character(1))
  header <- paste0("| ", paste(cols, collapse = " | "), " |")
  sep    <- paste0("| ", paste(rep("---", length(cols)), collapse = " | "), " |")
  paste(c(header, sep, body), collapse = "\n")
}
orci <- function(dt) { dt <- copy(dt); dt[, `OR (95% CI)` := sprintf("%.2f (%.2f-%.2f)", or, or_lci, or_uci)]; dt }

# Paper §9 anchors (per SD lower non-HDL): all-cause dementia + IHD.
PAPER <- data.table(
  gene = c("HMGCR","NPC1L1","ANGPTL4","LPL","PCSK9","CETP"),
  dementia_all = c("0.59 (0.35-0.99)","0.43 (0.14-1.33)","1.08 (0.50-2.32)",
                   "1.60 (1.01-2.55)","1.03 (0.90-1.17)","0.54 (0.37-0.78)"),
  ihd = c("0.41 (0.30-0.55)","0.65 (0.34-1.23)","0.23 (0.15-0.36)",
          "0.48 (0.37-0.62)","0.63 (0.58-0.68)","0.49 (0.40-0.60)"))

write_results_md <- function(allpe, est, diag, denovo_report, denovo_mr, disclaimer,
                             path = file.path(DIR_RESULTS, "RESULTS.md")) {
  main <- as.data.table(allpe)[exposure_trait == "nonHDL"]
  out <- c()
  add <- function(...) out <<- c(out, ...)

  add("# Results — lipid drug-target → dementia (2SMR, GLGC × FinnGen R12)", "",
      paste0("> **", disclaimer, "**"), "",
      "Companion to [../plan.md](../plan.md) and [../research.md](../research.md). ",
      "All ORs are **per 1 SD lower** exposure. Generated by `run_phase2.R`.", "")

  # Positive control
  ihd <- main[outcome == "ihd" & !is.na(or)]
  prot <- ihd[gene %in% c("HMGCR","LPL","PCSK9","CETP") & or < 1, gene]
  add("## Positive control (IHD)", "",
      sprintf("Anti-atherogenic targets protective for IHD (OR<1): **%s**. %s", paste(prot, collapse = ", "),
              if (length(prot) >= 3) "**PASS** — dementia estimates interpretable." else "**CHECK harmonization.**"),
      "")

  # Main results by outcome
  add("## Main analysis — per 1 SD lower non-HDL cholesterol", "")
  for (oc in unique(main$outcome)) {
    d <- orci(main[outcome == oc])
    add(sprintf("### %s", oc), "",
        md_table(d, c("gene","n_snp","method","OR (95% CI)","pval","min_F")), "")
  }

  # Concordance vs paper §9
  add("## Concordance with the paper (§9 anchors)", "",
      "Paper values include UKB+Copenhagen, so exact match is not expected; direction and rough magnitude are the check.", "")
  cmp <- merge(
    orci(main[outcome == "dementia_all", .(gene, or, or_lci, or_uci)])[, .(gene, ours_dementia = `OR (95% CI)`)],
    orci(main[outcome == "ihd", .(gene, or, or_lci, or_uci)])[, .(gene, ours_ihd = `OR (95% CI)`)], by = "gene")
  cmp <- merge(cmp, PAPER, by = "gene")
  setnames(cmp, c("dementia_all","ihd"), c("paper_dementia","paper_ihd"))
  add(md_table(cmp, c("gene","ours_dementia","paper_dementia","ours_ihd","paper_ihd")), "")

  # Sensitivity exposures
  sens <- as.data.table(allpe)[exposure_trait != "nonHDL" & !is.na(or)]
  add("## Sensitivity: target-specific exposure (LDL / logTG)", "",
      "LDL for HMGCR/NPC1L1/PCSK9/CETP; logTG for ANGPTL4/LPL (GLGC logTG is per-SD, not per-halving — see deviations).", "",
      md_table(orci(sens), c("gene","exposure_trait","outcome","n_snp","method","OR (95% CI)","pval")), "")

  # Estimators
  add("## Sensitivity estimators (multi-SNP genes: PCSK9, CETP)", "",
      md_table(orci(as.data.table(est)[!is.na(or)]),
               c("gene","outcome","n_snp","method","OR (95% CI)","pval")), "")

  # Diagnostics
  add("## Assumption checks (pleiotropy & heterogeneity)", "",
      "Egger intercept ≈ 0 (P>0.05) → little directional pleiotropy; Cochran's Q P>0.05 → no excess heterogeneity.", "",
      md_table(as.data.table(diag),
               c("gene","outcome","n_snp","egger_intercept","egger_intercept_p","Q","Q_pval")), "")

  # De-novo
  if (!is.null(denovo_report)) {
    add("## De-novo instrument selection (cis window + LD clump r²≤0.05, F>10)", "",
        "Reproduces the paper's *selection method* locally (cis window → GWAS-sig → clump r²≤0.05 → F>10).",
        "`named_sig` = paper's named rsIDs that are GWAS-significant here; `named_lead` = those that survive as an independent clump lead.",
        "Recovery is partial because the paper hand-picked 1–3 instruments, whereas de-novo r²≤0.05 keeps every independent cis signal (often more).", "",
        md_table(as.data.table(denovo_report),
                 c("gene","trait","n_cand","n_clumped","named_n","named_sig","named_lead","note")), "")
    if (!is.null(denovo_mr))
      add("### MR with de-novo instruments (per 1 SD lower non-HDL)", "",
          md_table(orci(as.data.table(denovo_mr)[!is.na(or)]),
                   c("gene","outcome","n_snp","method","OR (95% CI)","pval")), "")
  } else {
    add("## De-novo instrument selection", "", "_Skipped — LD panel not present at run time._", "")
  }

  # Deviations
  add("## Documented deviations from the paper", "",
      "- **Outcome = FinnGen R12 only** (no UKB/Copenhagen/UKB meta-analysis) → wider CIs, attenuated dementia effects.",
      "- **Per 1 SD** lower exposure (GLGC betas are per-SD), not per 1 mmol/L.",
      "- **logTG sensitivity reported per-SD**, not per-halving of triglycerides.",
      "- **No cross-cohort meta-analysis** (single outcome source).", "")

  writeLines(out, path)
  cat("wrote", path, "\n")
}

# ---- Phase 3 extension writeup -----------------------------------------------
write_phase3_md <- function(ad, meta, path = file.path(DIR_RESULTS, "RESULTS_phase3.md")) {
  ad <- as.data.table(ad); out <- c(); add <- function(...) out <<- c(out, ...)
  add("# Phase 3 (EXTENSION) — AD power boost with independent GWAS", "",
      "> **⚠ NOT a reproduction of the paper.** Bellenguez 2022 and Kunkle 2019 were **not** used by",
      "> Nordestgaard et al. Their AD outcomes were Copenhagen, UK Biobank, and FinnGen. This phase asks a",
      "> *different, stronger* question — does the GLGC→AD signal hold in larger, independent AD GWAS? —",
      "> and is kept separate from the reproduction tables in `RESULTS.md`.", "",
      "Same exposure instruments as Phases 1–2 (non-HDL, per 1 SD lower). Only the AD outcome source changes.", "",
      "| AD outcome GWAS | ~cases | notes |", "| --- | --- | --- |",
      "| FinnGen R12 (`F5_...`/`G6_ALZHEIMER`) | ~6,145 | the reproduction outcome |",
      "| Kunkle 2019 (`ieu-b-2`) | ~21,982 | clinically diagnosed, no UKB, no proxy — clean sensitivity |",
      "| Bellenguez 2022 (`ebi-a-GCST90027158`) | ~39,106 + proxy | largest; **includes** the Kunkle/IGAP samples |", "")

  add("## AD estimate by outcome source (per 1 SD lower non-HDL)", "",
      md_table(orci(ad[!is.na(or)]), c("gene","source","n_snp","method","OR (95% CI)","pval")), "")

  if (!is.null(meta) && nrow(meta)) {
    add("## Meta-analysis: FinnGen + Bellenguez (fixed-effect, inverse-variance)", "",
        "Pooled because FinnGen (Finnish) and Bellenguez are effectively non-overlapping. **Kunkle is NOT pooled**",
        "with Bellenguez — Bellenguez already contains the Kunkle/IGAP samples, so pooling would double-count.",
        "`Q_pval` < 0.05 would flag disagreement between the two sources.", "",
        md_table(orci(as.data.table(meta)), c("gene","k_sources","OR (95% CI)","pval","Q_pval","sources")), "")
  }

  add("## Reading this", "",
      "- Precision should **increase** (narrower CIs) moving FinnGen → Kunkle → Bellenguez as cases grow.",
      "- Direction agreement across independent GWAS is the real signal; a source-specific flip warrants caution.",
      "- Overlap caveats: exposure is `without_UKB` GLGC, so no exposure/outcome overlap even though Bellenguez",
      "  includes UK Biobank (proxy). Bellenguez's proxy phenotype is a slightly different estimand than clinical AD.", "")
  writeLines(out, path); cat("wrote", path, "\n")
}
